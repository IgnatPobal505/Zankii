import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const destination = resolve(root, 'ios/Zankii/Web');
const sourceNames = ['engine.js', 'render.js', 'game.js', 'index.html', 'styles.css', 'favicon.svg'];
const hash = content => createHash('sha256').update(content).digest('hex');

// This deliberately supports only our small, local module graph. Fail instead of
// silently shipping an incomplete offline app when a new import syntax is added.
export function bundleModules(sources) {
  const modules = new Map();
  const chunks = [];
  for (const filename of ['engine.js', 'render.js', 'game.js']) {
    const exports = [];
    let code = sources[filename].replace(/^import\s*\{([^}]+)\}\s*from\s*['"]\.\/([\w-]+\.js)(?:\?[^'"]*)?['"];?\s*$/gm, (_, names, dependency) => {
      if (!modules.has(dependency)) throw new Error(`${filename}: unsupported dependency ${dependency}`);
      const bindings = names.split(',').map(name => name.trim()).filter(Boolean);
      for (const binding of bindings) {
        if (!/^[A-Za-z_$][\w$]*$/.test(binding) || !modules.get(dependency).includes(binding)) throw new Error(`${filename}: unsupported import ${binding}`);
      }
      return `const { ${bindings.join(', ')} } = modules[${JSON.stringify(dependency)}];`;
    });
    code = code.replace(/^export\s+(const|let|function|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kind, name) => {
      exports.push(name);
      return `${kind} ${name}`;
    });
    if (/^\s*(?:import|export)\b/m.test(code) || /\bimport\s*\(/.test(code)) throw new Error(`${filename}: unsupported module syntax; update the offline packager`);
    modules.set(filename, exports);
    chunks.push(`// ${filename}\nmodules[${JSON.stringify(filename)}] = (() => {\n${code.trim()}\nreturn { ${exports.join(', ')} };\n})();`);
  }
  return `// Generated by scripts/sync-ios-web.mjs. Edit the root sources, then run npm run ios:sync.\n(() => {\n'use strict';\nconst modules = Object.create(null);\n${chunks.join('\n\n')}\n})();\n`;
}

export async function expectedFiles() {
  const contents = await Promise.all(sourceNames.map(name => readFile(resolve(root, name), 'utf8')));
  const sources = Object.fromEntries(sourceNames.map((name, i) => [name, contents[i]]));
  const script = /<script\s+type="module"\s+src="game\.js(?:\?[^\"]*)?"><\/script>/g;
  if ((sources['index.html'].match(script) || []).length !== 1) throw new Error('Expected one game module entry in index.html');
  const html = sources['index.html']
    .replace('<html lang="en">', '<html lang="en" class="native-ios">')
    .replace(/styles\.css\?v=[\w.-]+/g, 'styles.css')
    .replace(script, '<script defer src="zankii.js"></script>');
  const files = { 'index.html': html, 'styles.css': sources['styles.css'], 'favicon.svg': sources['favicon.svg'], 'zankii.js': bundleModules(sources) };
  const manifest = {
    format: 1,
    generator: 'scripts/sync-ios-web.mjs',
    sources: Object.fromEntries(sourceNames.map(name => [name, hash(sources[name])])),
    files: Object.fromEntries(Object.entries(files).map(([name, content]) => [name, hash(content)]))
  };
  files['manifest.json'] = `${JSON.stringify(manifest, null, 2)}\n`;
  return files;
}

export async function syncIOSWeb({ check = false } = {}) {
  const files = await expectedFiles();
  if (check) {
    const names = await readdir(destination).catch(() => []);
    const differences = names.filter(name => !Object.hasOwn(files, name));
    for (const [name, content] of Object.entries(files)) {
      const existing = await readFile(resolve(destination, name), 'utf8').catch(() => null);
      if (existing !== content) differences.push(name);
    }
    if (differences.length) throw new Error(`iOS Web assets are out of date (${[...new Set(differences)].join(', ')}). Run npm run ios:sync and commit the files.`);
  } else {
    await mkdir(destination, { recursive: true });
    for (const [name, content] of Object.entries(files)) await writeFile(resolve(destination, name), content);
  }
  return files;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    await syncIOSWeb({ check: process.argv.includes('--check') });
    console.log(process.argv.includes('--check') ? 'iOS offline assets match the game sources.' : 'Updated ios/Zankii/Web (offline, no runtime dependencies).');
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
